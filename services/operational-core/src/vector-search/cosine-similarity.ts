// Pure vector math — the actual "index" in this interim backend (see
// docs/architecture/vector-search.md). Returns 0 for mismatched dimensions
// or zero-vectors rather than throwing, since a corrupt/legacy embedding row
// should be filtered out of ranking, not crash the whole search.
export function cosineSimilarity(a: number[], b: number[]): number {
  if (a.length !== b.length || a.length === 0) return 0;

  let dot = 0;
  let normA = 0;
  let normB = 0;
  for (let i = 0; i < a.length; i++) {
    dot += a[i] * b[i];
    normA += a[i] * a[i];
    normB += b[i] * b[i];
  }

  if (normA === 0 || normB === 0) return 0;
  return dot / (Math.sqrt(normA) * Math.sqrt(normB));
}
